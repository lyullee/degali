def contact_index(prism):
    centre=np.array(prism.cloud.center_xy_m)
    for i in range(len(prism.states)):
        p=prism.vertices(i)
        candidates=list(p[p[:,0]>=centre[0]])
        for a,b in zip(p,np.roll(p,-1,axis=0)):
            if (a[0]-centre[0])*(b[0]-centre[0])<0:
                candidates.append(a+(b-a)*(centre[0]-a[0])/(b[0]-a[0]))
        if candidates and np.max(np.linalg.norm(np.array(candidates)-centre,axis=1))>=50:
            return i
    return None


